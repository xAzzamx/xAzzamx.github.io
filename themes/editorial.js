ThemeEngine.register("editorial", function(root){
  var E = ThemeEngine, S = E.site;
  var mast = E.h("header", "ed-mast");
  mast.appendChild(E.h("p", "ed-issue", E.isAr() ? "العدد 01  |  ملف الخريج" : "ISSUE 01  |  GRADUATE FILE"));
  mast.appendChild(E.h("h1", "", E.t(S.name)));
  mast.appendChild(E.h("p", "", E.t(S.role)));
  root.appendChild(mast);
  if (E.page === "certs"){
    root.appendChild(E.h("h2", "", E.isAr() ? "فهرس الشهادات" : "Certificate index"));
    root.appendChild(E.backLink());
    E.rails(root, {rowClass:"ed-row", railClass:"ed-rail", cardClass:"ed-card"});
    return;
  }
  var wrap = E.h("div", "ed-wrap");
  var toc = E.h("nav", "ed-toc");
  toc.appendChild(E.h("p", "ed-kicker", E.isAr() ? "المحتويات" : "CONTENTS"));
  [["#ed-essay", {en:"Essay", ar:"المقال"}],["#ed-record", {en:"Record", ar:"السجل"}],["#ed-work", {en:"Work", ar:"الأعمال"}],["#ed-certs", {en:"Certificates", ar:"الشهادات"}],["#ed-note", {en:"Correspondence", ar:"مراسلة"}]].forEach(function(item, i){
    var a = E.h("a", "");
    a.href = item[0];
    a.appendChild(E.h("span", "", "0" + (i + 1) + "  "));
    a.appendChild(E.bi(item[1].en, item[1].ar));
    toc.appendChild(a);
  });
  var essay = E.h("article", "ed-essay");
  essay.id = "ed-essay";
  essay.appendChild(E.h("p", "ed-kicker", E.t(S.status)));
  essay.appendChild(E.h("p", "ed-drop", E.t(S.lead)));
  essay.appendChild(E.h("blockquote", "", E.t(S.quote)));
  S.about.forEach(function(p){ essay.appendChild(E.h("p", "", E.t(p))); });
  wrap.appendChild(toc);
  wrap.appendChild(essay);
  root.appendChild(wrap);
  var rec = E.h("section", "ed-cols");
  rec.id = "ed-record";
  var c1 = E.h("div", "");
  c1.appendChild(E.h("h2", "", E.t(S.edu.title)));
  c1.appendChild(E.h("p", "", E.t(S.edu.where)));
  c1.appendChild(E.h("p", "", E.t(S.edu.note)));
  var c2 = E.h("div", "");
  c2.appendChild(E.h("h2", "", E.t(S.job.title)));
  c2.appendChild(E.h("p", "", E.t(S.job.where)));
  S.job.bullets.forEach(function(b){ c2.appendChild(E.h("p", "", E.t(b))); });
  rec.appendChild(c1); rec.appendChild(c2);
  root.appendChild(rec);
  var work = E.h("section", "");
  work.id = "ed-work";
  S.projects.forEach(function(p, i){
    var f = E.h("article", "ed-feature");
    f.appendChild(E.h("p", "ed-kicker", "0" + (i + 1)));
    f.appendChild(E.h("h2", "", E.t(p.title)));
    f.appendChild(E.h("p", "", E.t(p.body)));
    work.appendChild(f);
  });
  root.appendChild(work);
  var certs = E.h("section", "ed-certs");
  certs.id = "ed-certs";
  certs.appendChild(E.h("h2", "", E.isAr() ? "الشهادات" : "Certificates"));
  certs.appendChild(E.h("p", "", (E.isAr() ? "صفوف حسب المجال، العدد " : "Rows by field, count ") + E.count()));
  var a = E.h("a", ""); a.href = "certificates.html"; a.appendChild(E.bi("Open the certificate index", "افتح فهرس الشهادات"));
  certs.appendChild(a);
  root.appendChild(certs);
  var note = E.h("section", "ed-note");
  note.id = "ed-note";
  note.appendChild(E.h("h2", "", E.isAr() ? "مراسلة" : "Correspondence"));
  note.appendChild(E.h("p", "", S.links.email));
  note.appendChild(E.form());
  root.appendChild(note);
});
